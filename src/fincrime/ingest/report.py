"""A fact sheet of the benchmark datasets actually on disk, generated from the Parquet files.

Everything in the report is measured on the converted data (not copied from a paper), next to
the licence and the rule for what may be published.
"""

from __future__ import annotations

from pathlib import Path

import duckdb

from fincrime import config
from fincrime.ingest.sources import SOURCES


def _q(path: Path) -> str:
    return path.as_posix().replace("'", "''")


def _one(sql: str) -> tuple:
    return duckdb.sql(sql).fetchall()[0]


def amlworld_rows(folder: Path) -> list[dict]:
    """One row per HI/LI x size that has been converted."""
    rows = []
    for trans in sorted(folder.glob("*-*_Trans.parquet")):
        name = trans.name.removesuffix("_Trans.parquet")  # e.g. HI-Small
        n, pos, t0, t1, accts = _one(
            f"select count(*), sum(is_laundering), min(ts), max(ts), count(distinct from_account) "
            f"from read_parquet('{_q(trans)}')"
        )
        row = {
            "dataset": name,
            "transactions": n,
            "laundering": int(pos),
            "laundering_pct": 100 * pos / n,
            "first": t0,
            "last": t1,
            "senders": accts,
            "pattern_txns": None,
            "pattern_types": None,
        }
        pat = folder / f"{name}_Patterns.parquet"
        if pat.exists():
            ptx, ptypes = _one(
                f"select count(*), count(distinct pattern_type) from read_parquet('{_q(pat)}')"
            )
            row["pattern_txns"], row["pattern_types"] = ptx, ptypes
        rows.append(row)
    return rows


def baf_rows(folder: Path) -> list[dict]:
    """One row per BAF variant."""
    files = sorted(folder.glob("*.parquet"))
    if not files:
        return []
    out = []
    for variant, n, pct, m0, m1 in duckdb.sql(
        f"select variant, count(*), avg(fraud_bool) * 100, min(month), max(month) "
        f"from read_parquet('{_q(folder)}/*.parquet') group by 1 order by 1"
    ).fetchall():
        out.append({"variant": variant, "rows": n, "fraud_pct": pct, "months": f"{m0} to {m1}"})
    return out


def sparkov_rows(folder: Path) -> list[dict]:
    """One row per Sparkov split."""
    if not list(folder.glob("*.parquet")):
        return []
    q = (
        "select split, count(*), avg(is_fraud) * 100, min(trans_date_trans_time), "
        "max(trans_date_trans_time), count(distinct cc_num) "
        f"from read_parquet('{_q(folder)}/*.parquet') group by 1 order by 1 desc"
    )
    return [
        {"split": s, "rows": n, "fraud_pct": p, "first": a, "last": b, "cards": c}
        for s, n, p, a, b, c in duckdb.sql(q).fetchall()
    ]


def render_markdown(processed: Path | None = None) -> str:
    """The Markdown fact sheet for whatever has been converted so far."""
    base = processed or config.get_paths().processed
    lines = [
        "# Benchmark datasets on disk",
        "",
        "Generated by `fincrime ingest report` from the converted Parquet files. Raw data is never",
        "committed or republished; the publish rule of each source is stated below.",
        "",
    ]
    aml = amlworld_rows(base / "amlworld")
    lines += [
        "## IBM AMLworld",
        "",
        f"Licence: {SOURCES['amlworld'].license}. Publish rule: {SOURCES['amlworld'].publish_rule}.",
        "",
    ]
    if aml:
        lines += [
            "| Dataset | Transactions | Laundering | Rate | Span | Pattern txns | Pattern coverage | Pattern types |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for r in aml:
            cover = "" if r["pattern_txns"] is None else f"{r['pattern_txns']:,}"
            share = (
                ""
                if r["pattern_txns"] is None
                else f"{100 * r['pattern_txns'] / r['laundering']:.0f}%"
            )
            kinds = "" if r["pattern_types"] is None else str(r["pattern_types"])
            lines.append(
                f"| {r['dataset']} | {r['transactions']:,} | {r['laundering']:,} | "
                f"{r['laundering_pct']:.4f}% | {r['first']:%Y-%m-%d} to {r['last']:%Y-%m-%d} | "
                f"{cover} | {share} | {kinds} |"
            )
        lines += [
            "",
            "The pattern files list only the schemes the generator planted as such: some",
            "laundering-labelled transactions belong to no listed scheme, so coverage figures",
            "must name their denominator.",
        ]
    else:
        lines.append("Not downloaded yet.")

    baf = baf_rows(base / "baf")
    lines += [
        "",
        "## Bank Account Fraud, NeurIPS 2022",
        "",
        f"Licence: {SOURCES['baf'].license}. Publish rule: {SOURCES['baf'].publish_rule}.",
        "",
    ]
    if baf:
        lines += ["| Variant | Rows | Fraud rate | Months |", "|---|---|---|---|"]
        lines += [
            f"| {r['variant']} | {r['rows']:,} | {r['fraud_pct']:.3f}% | {r['months']} |"
            for r in baf
        ]
    else:
        lines.append("Not downloaded yet.")

    sp = sparkov_rows(base / "sparkov")
    lines += [
        "",
        "## Sparkov synthetic card fraud",
        "",
        f"Licence: {SOURCES['sparkov'].license}. Publish rule: {SOURCES['sparkov'].publish_rule}.",
        "",
    ]
    if sp:
        lines += ["| Split | Rows | Fraud rate | Span | Cards |", "|---|---|---|---|---|"]
        lines += [
            f"| {r['split']} | {r['rows']:,} | {r['fraud_pct']:.3f}% | "
            f"{r['first']:%Y-%m-%d} to {r['last']:%Y-%m-%d} | {r['cards']:,} |"
            for r in sp
        ]
    else:
        lines.append("Not downloaded yet.")

    ieee = base / "ieee_cis" / "train_transaction.parquet"
    lines += [
        "",
        "## IEEE-CIS Fraud Detection",
        "",
        f"Licence: {SOURCES['ieee_cis'].license}. Publish rule: {SOURCES['ieee_cis'].publish_rule}.",
        "",
    ]
    if ieee.exists():
        n, pct = _one(f"select count(*), avg(isFraud) * 100 from read_parquet('{_q(ieee)}')")
        lines.append(f"{n:,} transactions, {pct:.2f}% fraud.")
    else:
        lines.append("Not downloaded yet: the competition rules must be accepted on Kaggle first.")
    return "\n".join(lines) + "\n"
